"""План сборки структуры по частям (compositional structured output).

Рекурсивная модель «как собрать значение по этой JSON-схеме»: вместо одного
strict-вызова на всю сложную схему — дерево узлов, каждый из которых собирается
отдельным простым запросом и детерминированно склеивается.

Три вида узлов (sealed-иерархия `FieldPlan`):

* :class:`LeafPlan` — сгенерировать значение целиком одним вызовом. Применяется
  к листовым типам, простым объектам и простым массивам — тому, что модель
  уверенно отдаёт за один проход.
* :class:`ObjectPlan` — объект собирается по полям: сначала «структурные» поля
  (вложенные объекты/массивы) каждое своим под-планом, ПОТОМ оставшиеся скаляры
  одним вызовом. Порядок «структурное → скаляры» неслучаен: скаляр, ссылающийся
  на список (напр. ``proposed_option_id`` ∈ ``alternatives``), генерируется уже
  ВИДЯ собранный список — так кросс-полевая согласованность достигается порядком,
  а не надеждой.
* :class:`ArrayPlan` — массив объектов по схеме «каркас → наполнение»: сначала
  спрашиваем «сколько и какие» (ядро каждого элемента), затем достраиваем каждый
  элемент его под-планом. Снимает патологию «генерирует, чтобы заполнить
  maxItems».

Все узлы — неизменяемые dataclass'ы (чистые данные, без I/O). Их строит
:mod:`decomposer`, исполняет :mod:`assembler`.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

JSONSchema = dict[str, Any]


@dataclass(frozen=True)
class FieldPlan:
    """База sealed-иерархии планов поля. Не инстанцируется напрямую."""


@dataclass(frozen=True)
class LeafPlan(FieldPlan):
    """Сгенерировать значение поддерева целиком одним вызовом.

    Лист декомпозиции: схема достаточно проста, чтобы модель отдала её за один
    проход (скаляр, enum, простой объект из скаляров, массив скаляров)."""

    schema: JSONSchema


@dataclass(frozen=True)
class ObjectPlan(FieldPlan):
    """Объект, собираемый по полям.

    ``structural`` — поля с собственным под-планом (вложенные объекты/массивы
    объектов), в порядке генерации. ``scalar_groups`` — БАТЧИ простых полей:
    каждый батч это под-схема ``object`` из нескольких полей, генерируемая ОДНИМ
    вызовом ПОСЛЕ всех structural. Дробление на батчи (а не один общий вызов на
    все простые поля) — ключевое: плоский объект с десятками полей strict не
    берёт за раз (штормит coercion), а батч из нескольких полей берёт надёжно.
    ``schema`` — исходная схема объекта (для скелета-контекста)."""

    schema: JSONSchema
    structural: tuple[tuple[str, FieldPlan], ...]
    scalar_groups: tuple[JSONSchema, ...]


@dataclass(frozen=True)
class ArrayPlan(FieldPlan):
    """Массив объектов по схеме «каркас → наполнение».

    ``outline_schema`` — под-схема ответа-каркаса (``{items: [<ядро>]}`` с
    минимумом полей на элемент); по нему узнаём число и ядро элементов.
    ``item_plan`` — план достройки одного элемента (его «ядро» подаётся как seed).
    ``schema`` — исходная схема массива (constraints/валидация)."""

    schema: JSONSchema
    outline_schema: JSONSchema
    item_plan: FieldPlan
