"""Сборка промпта для генерации ОДНОГО фрагмента структуры.

Самое тонкое место подхода: фрагмент, вырванный из контекста, генерится
несогласованно. Поэтому промпт фрагмента несёт:

1. исходную роль/стиль (``base_system`` — сохраняем как есть);
2. исходный контекст задачи (``base_user`` — идёт ПЕРВЫМ, чтобы общий префикс
   попадал в prompt-кэш и фрагменты платили только за свою дельту);
3. «скелет целого» — частично собранный объект с явным плейсхолдером на месте
   текущего вклада: модель видит, куда встанет её ответ и что уже определено
   (отсюда согласованность, в т.ч. ссылки на уже собранные списки);
4. фокус-инструкцию «верни ТОЛЬКО этот фрагмент»;
5. саму под-схему фрагмента добавляет уже провайдер (``chat_json``) — здесь её
   не дублируем.

Чистый строитель строк, без I/O и без LLM.
"""

from __future__ import annotations

import json
from typing import Any

# Маркер места текущего вклада в скелете целого. Видимый, человекочитаемый,
# заведомо не похож на реальное значение — модель понимает, что заполняет именно
# его.
PLACEHOLDER = "<<СГЕНЕРИРУЙ_ЭТОТ_ФРАГМЕНТ>>"

_ASSEMBLY_SYSTEM_NOTE = (
    "Ты собираешь большой структурированный объект ПО ЧАСТЯМ. На каждом шаге "
    "возвращай строго один запрошенный фрагмент в виде JSON по схеме фрагмента — "
    "без полей сверх запрошенных и без текста вне JSON. Держи фрагмент "
    "согласованным с уже собранным (показано в контексте)."
)


class PartPromptBuilder:
    """Строит ``(system, user)`` для генерации одного фрагмента структуры."""

    def build(
        self,
        *,
        base_system: str,
        base_user: str,
        focus_label: str,
        skeleton: Any,
        ancestor: dict[str, Any] | None = None,
    ) -> tuple[str, str]:
        system = (base_system.rstrip() + "\n\n" + _ASSEMBLY_SYSTEM_NOTE) if base_system else _ASSEMBLY_SYSTEM_NOTE
        ancestor_block = ""
        if ancestor:
            ancestor_json = json.dumps(ancestor, ensure_ascii=False, indent=2)
            ancestor_block = (
                "\nЭтот фрагмент относится к уже определённому родительскому "
                f"элементу:\n{ancestor_json}\n"
            )
        skeleton_json = json.dumps(skeleton, ensure_ascii=False, indent=2)
        assembly_block = (
            "\n\n--- СБОРКА ПО ЧАСТЯМ ---\n"
            f"Целевой объект собирается по фрагментам.{ancestor_block}\n"
            f"Уже собранное (на месте {PLACEHOLDER} — твой текущий вклад):\n\n"
            f"{skeleton_json}\n\n"
            f"Сейчас сгенерируй ТОЛЬКО фрагмент: {focus_label}.\n"
            "Верни его как JSON по схеме фрагмента (ниже), согласованным с уже "
            "собранным выше (в т.ч. ссылки на уже перечисленные элементы)."
        )
        user = (base_user.rstrip() + assembly_block) if base_user else assembly_block.lstrip()
        return system, user
